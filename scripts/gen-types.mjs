// Generates src/lib/database.generated.ts (Supabase `Database` shape) from the migrations,
// using PGlite instead of a running Supabase/Docker. src/lib/database.check.ts asserts the
// hand-written types in database.types.ts stay in sync with it.
import { writeFileSync } from 'node:fs';
import { migratedDb } from './migrated-db.mjs';

const OUT = 'src/lib/database.generated.ts';
const db = await migratedDb();
const q = async (sql) => (await db.query(sql)).rows;

const SCALAR = {
  uuid: 'string', text: 'string', varchar: 'string', bpchar: 'string', date: 'string', time: 'string', timetz: 'string',
  timestamp: 'string', timestamptz: 'string', interval: 'string',
  int2: 'number', int4: 'number', int8: 'number', float4: 'number', float8: 'number', numeric: 'number',
  bool: 'boolean', json: 'Json', jsonb: 'Json', void: 'undefined',
};
const tsType = (udt) => {
  if (udt.startsWith('_')) return `${tsType(udt.slice(1))}[]`;
  const t = SCALAR[udt];
  if (!t) throw new Error(`No TS mapping for Postgres type "${udt}"`);
  return t;
};

const columns = await q(`
  select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
         (c.column_default is not null or c.is_identity = 'YES') as has_default, t.table_type
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public'
  order by c.table_name, c.ordinal_position`);

const relations = {};
for (const c of columns) (relations[c.table_name] ??= { view: c.table_type === 'VIEW', cols: [] }).cols.push(c);

// Callable RPCs only: skip trigger functions and anything revoked from `authenticated`.
const fns = await q(`
  select p.proname as name, p.proargnames as arg_names, p.pronargs as nargs, p.pronargdefaults as ndefaults,
         array(select format_type(t, null) from unnest(p.proargtypes) t) as arg_types,
         (select typname from pg_type where oid = p.prorettype) as ret, p.proretset as setof
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prorettype <> 'trigger'::regtype
    and has_function_privilege('authenticated', p.oid, 'execute')
  order by p.proname`);
const typeByFormat = (f) => {
  const arr = f.endsWith('[]');
  const base = f.replace('[]', '');
  const udt = { 'character varying': 'varchar', 'timestamp with time zone': 'timestamptz', 'timestamp without time zone': 'timestamp',
    'time without time zone': 'time', integer: 'int4', bigint: 'int8', smallint: 'int2', boolean: 'bool', 'double precision': 'float8', real: 'float4' }[base] ?? base;
  return tsType(arr ? `_${udt}` : udt);
};

const ind = (n) => '  '.repeat(n);
const field = (name, type, opt) => `${name}${opt ? '?' : ''}: ${type}`;
let out = `// Generated by scripts/gen-types.mjs from supabase/migrations — do not edit. Run \`npm run gen:types\`.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]

export type Database = {
  public: {
`;
for (const kind of ['Tables', 'Views']) {
  out += `${ind(2)}${kind}: {\n`;
  for (const [name, rel] of Object.entries(relations)) {
    if (rel.view !== (kind === 'Views')) continue;
    // Postgres can't prove view columns non-null, so (like supabase gen) they are all nullable.
    const row = rel.cols.map((c) => field(c.column_name, tsType(c.udt_name) + (c.nullable || rel.view ? ' | null' : ''), false));
    out += `${ind(3)}${name}: {\n${ind(4)}Row: { ${row.join('; ')} }\n`;
    if (!rel.view) {
      const ins = rel.cols.map((c) => field(c.column_name, tsType(c.udt_name) + (c.nullable ? ' | null' : ''), c.nullable || c.has_default));
      const upd = rel.cols.map((c) => field(c.column_name, tsType(c.udt_name) + (c.nullable ? ' | null' : ''), true));
      out += `${ind(4)}Insert: { ${ins.join('; ')} }\n${ind(4)}Update: { ${upd.join('; ')} }\n`;
    }
    out += `${ind(4)}Relationships: []\n${ind(3)}}\n`;
  }
  out += `${ind(2)}}\n`;
}
out += `${ind(2)}Functions: {\n`;
for (const f of fns) {
  const names = f.arg_names ?? [];
  const firstOptional = f.nargs - f.ndefaults;
  const args = f.arg_types.map((t, i) => field(names[i] ?? `arg${i}`, typeByFormat(t), i >= firstOptional));
  const ret = f.ret === 'record' ? 'Record<string, unknown>[]' : tsType(f.ret) + (f.setof ? '[]' : '');
  out += `${ind(3)}${f.name}: { Args: ${args.length ? `{ ${args.join('; ')} }` : 'Record<string, never>'}; Returns: ${ret} }\n`;
}
out += `${ind(2)}}\n${ind(2)}Enums: Record<string, never>\n${ind(2)}CompositeTypes: Record<string, never>\n  }\n}\n`;

writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${Object.keys(relations).length} tables/views, ${fns.length} functions`);
